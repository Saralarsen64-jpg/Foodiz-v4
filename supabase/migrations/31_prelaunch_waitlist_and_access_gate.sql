CREATE OR REPLACE FUNCTION public.foodiz_app_is_launched()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(
    (SELECT (value ->> 'launched')::boolean
     FROM public.app_settings
     WHERE key = 'launch_status'),
    false
  );
$$;

CREATE OR REPLACE FUNCTION public.foodiz_application_access_allowed()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    public.current_user_has_role('admin')
    OR (
      public.foodiz_app_is_launched()
      AND (
        NOT EXISTS (
          SELECT 1
          FROM public.prelaunch_profiles
          WHERE user_id = auth.uid()
        )
        OR EXISTS (
          SELECT 1
          FROM public.prelaunch_profiles
          WHERE user_id = auth.uid()
            AND status = 'activated'
        )
      )
    );
$$;

REVOKE ALL ON FUNCTION public.foodiz_app_is_launched() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.foodiz_application_access_allowed() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.foodiz_app_is_launched() TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.foodiz_application_access_allowed() TO anon, authenticated, service_role;

-- A restrictive policy is combined with every existing permissive policy.
-- It blocks anonymous and authenticated application data access before launch,
-- while service_role keeps its normal RLS bypass for controlled server routes.
DO $$
DECLARE
  target record;
BEGIN
  FOR target IN
    SELECT namespace.nspname AS schemaname, relation.relname AS tablename
    FROM pg_class relation
    JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = 'public'
      AND relation.relkind = 'r'
      AND relation.relrowsecurity = true
      AND relation.relname NOT IN (
        'app_settings',
        'prelaunch_profiles',
        'prelaunch_partner_details',
        'prelaunch_driver_details',
        'prelaunch_registration_attempts'
      )
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      'foodiz_prelaunch_global_gate',
      target.schemaname,
      target.tablename
    );
    EXECUTE format(
      'CREATE POLICY %I ON %I.%I AS RESTRICTIVE FOR ALL TO anon, authenticated USING (public.foodiz_application_access_allowed()) WITH CHECK (public.foodiz_application_access_allowed())',
      'foodiz_prelaunch_global_gate',
      target.schemaname,
      target.tablename
    );
  END LOOP;
END;
$$;
