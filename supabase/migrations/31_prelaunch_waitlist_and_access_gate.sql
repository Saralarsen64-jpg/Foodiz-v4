-- Weello pre-launch mode:
-- - public launch status;
-- - Auth-linked pre-registrations;
-- - admin-only global visibility;
-- - restrictive access gate for every existing application table.

CREATE TABLE IF NOT EXISTS public.app_settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.app_settings (key, value)
VALUES ('launch_status', '{"launched": false}'::jsonb)
ON CONFLICT (key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.prelaunch_profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('client', 'livreur', 'partenaire')),
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL,
  city text NOT NULL,
  status text NOT NULL DEFAULT 'prelaunch_pending'
    CHECK (status IN ('prelaunch_pending', 'launch_email_sent', 'activated', 'rejected')),
  marketing_consent boolean NOT NULL DEFAULT false,
  consent_at timestamptz,
  launch_token text UNIQUE,
  launch_token_expires_at timestamptz,
  launch_notified_at timestamptz,
  activated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS prelaunch_profiles_email_unique_ci
  ON public.prelaunch_profiles (lower(email));

CREATE INDEX IF NOT EXISTS prelaunch_profiles_status_idx
  ON public.prelaunch_profiles (status, created_at);

CREATE TABLE IF NOT EXISTS public.prelaunch_partner_details (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  prelaunch_profile_id uuid NOT NULL UNIQUE
    REFERENCES public.prelaunch_profiles(id) ON DELETE CASCADE,
  establishment_name text NOT NULL,
  establishment_type text NOT NULL
    CHECK (establishment_type IN ('restaurant', 'market', 'epicerie', 'autre')),
  siret text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.prelaunch_driver_details (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  prelaunch_profile_id uuid NOT NULL UNIQUE
    REFERENCES public.prelaunch_profiles(id) ON DELETE CASCADE,
  vehicle_type text NOT NULL
    CHECK (vehicle_type IN ('velo', 'scooter', 'voiture', 'autre')),
  availability text NOT NULL
    CHECK (availability IN ('journee', 'soiree', 'nuit', 'week_end')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Server-only anti-abuse ledger. No client policy is intentionally granted.
CREATE TABLE IF NOT EXISTS public.prelaunch_registration_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint_hash text NOT NULL,
  email_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS prelaunch_registration_attempts_lookup_idx
  ON public.prelaunch_registration_attempts (fingerprint_hash, created_at DESC);

CREATE OR REPLACE FUNCTION public.set_prelaunch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_prelaunch_profiles_updated_at ON public.prelaunch_profiles;
CREATE TRIGGER set_prelaunch_profiles_updated_at
BEFORE UPDATE ON public.prelaunch_profiles
FOR EACH ROW EXECUTE FUNCTION public.set_prelaunch_updated_at();

